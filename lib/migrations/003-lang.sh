#!/usr/bin/env bash
# v3 — lang 을 채운다.
#
# 왜 필요한가:
#   0.3.0 부터 폴더 이름·허브 본문이 lang 을 따른다. 이 키가 없으면
#   dt_lang 이 매번 로케일을 다시 본다. 사용자가 로케일을 바꾸거나
#   cron/launchd 처럼 로케일이 없는 환경에서 실행하면 **같은 볼트에
#   다른 언어의 폴더가 생긴다.**
#
# 안전 기본값:
#   기존 설정은 전부 한국어 볼트다 — 0.2.x 에는 영어가 없었다.
#   로케일을 보지 않고 ko 로 못 박는다. 여기서 로케일을 보면
#   영어 로케일 사용자의 한국어 볼트 옆에 영어 폴더가 생긴다.

_mg_003_why="lang 을 채운다 (기존 볼트는 전부 ko)"

_mg_003() {
  local cfg="$1"
  jq 'if (has("lang") | not) then .lang = "ko" else . end' "$cfg"
}
